# ADR-001: Архітектурний рефакторинг системи медичної клініки

## Статус
Прийнято (Accepted)

## Дата
01.11.2026

## Контекст

Початкова версія системи медичної клініки була реалізована
у вигляді монолітного класу LegacyClinicService.

У початковому коді були виявлені такі проблеми:

1. Anemic Domain Model — класи Patient, Doctor та Appointment
   містили лише публічні поля без власної бізнес-логіки.
2. Порушення інкапсуляції — стан об'єктів можна було довільно
   змінювати ззовні.
3. Bloated Controller — консольний клас одночасно зчитував
   дані, створював об'єкти, виконував розрахунки та формував квитанції.
4. High Coupling — бізнес-логіка залежала від деталей
   реалізації зберігання та надсилання SMS.
5. Процедурні розгалуження — розрахунок вартості консультації
   залежав від категорії лікаря через if-else.
6. Низька згуртованість — різні обов'язки були зосереджені
   в одному класі.

## Рішення

Було прийнято рішення провести архітектурний рефакторинг
із використанням Rich Domain Model та GRASP.

Основні рішення:

### 1. Information Expert

Бізнес-логіку перенесено до об'єктів, які володіють
необхідними даними.

- Doctor.calculateConsultationCost() — розрахунок вартості консультації.
- Appointment.confirm() — підтвердження запису та розрахунок вартості.
- InsurancePolicy.calculateCoverage() — розрахунок страхового покриття.

### 2. Creator

Створення запису пацієнта реалізовано через
статичний метод Appointment.create().

### 3. Controller

Створено AppointmentController, який координує виконання
сценарію запису пацієнта на прийом.

### 4. Indirection

Для послаблення залежностей використано інтерфейси:

- AppointmentRepository;
- SmsSender;
- InvoiceGenerator.

### 5. Pure Fabrication

Створено технічні класи:

- InMemoryAppointmentRepository;
- ConsoleSmsSender;
- StandardInvoiceGenerator;
- ConsultationPricingFactory.

Вони виконують інфраструктурні обов'язки, не перевантажуючи
доменні сутності.

### 6. Polymorphism

Для розрахунку вартості консультації створено інтерфейс
ConsultationPricing та три реалізації:

- GeneralPricing;
- SpecialistPricing;
- ProfessorPricing.

### 7. Protected Variations

Змінні алгоритми розрахунку вартості та технічні механізми
зберігання й надсилання повідомлень ізольовані за допомогою
інтерфейсів.

### 8. Low Coupling

Залежності між шарами системи зменшено завдяки інтерфейсам
та розділенню відповідальностей.

### 9. High Cohesion

Кожен клас отримав чітку відповідальність:
доменні сутності керують бізнес-станом, інфраструктурні
класи виконують технічні операції, а UI відповідає
за взаємодію з користувачем.

## Альтернативи

### Варіант 1: Залишити монолітний LegacyClinicService

Переваги:
- Простота початкової реалізації.
- Мінімальні витрати на зміни.

Недоліки:
- Високе зчеплення.
- Низька згуртованість.
- Складність тестування та розширення.

### Варіант 2: Використати Rich Domain Model та GRASP

Переваги:
- Інкапсуляція бізнес-логіки.
- Розділення відповідальностей.
- Можливість заміни технічних реалізацій.
- Краща тестованість та розширюваність.

Недоліки:
- Більша кількість класів та інтерфейсів.
- Необхідність початкового архітектурного проєктування.

## Наслідки

Позитивні:
- Усунуто основні ознаки Anemic Domain Model.
- Бізнес-логіку перенесено до доменних сутностей.
- Зменшено залежність від конкретних інфраструктурних реалізацій.
- Процедурний розрахунок вартості замінено поліморфізмом.
- Покращено згуртованість класів.

Негативні:
- Збільшилася кількість класів.
- З'явилися додаткові інтерфейси та абстракції.
- Потрібно підтримувати узгодженість між шарами системи.

## Висновок

Для рефакторингу обрано Rich Domain Model із застосуванням
GRASP, оскільки такий підхід забезпечує краще розділення
відповідальностей, інкапсуляцію бізнес-логіки та можливість
розширення системи без суттєвих змін її основних компонентів.

Рішення відповідає принципам Low Coupling та High Cohesion.
